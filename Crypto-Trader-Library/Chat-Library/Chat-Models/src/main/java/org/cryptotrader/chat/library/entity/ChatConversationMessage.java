package org.cryptotrader.chat.library.entity;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.NoArgsConstructor;
import org.cryptotrader.chat.library.model.MessageAuthorSource;
import org.cryptotrader.universal.library.entity.AutoGeneratedIdentifiableEntity;
import org.jetbrains.annotations.NotNull;

/** A chat message with a bot via Crypto-Trader-Chat. */
@Entity
@Table(name = "chat_conversation_messages")
@NoArgsConstructor
@AllArgsConstructor
public class ChatConversationMessage extends AutoGeneratedIdentifiableEntity {
    @Column(name = "message_content", nullable = false)
    private @NotNull String messageContent;

    @ManyToOne
    @JoinColumn(name = "conversation_id", nullable = false)
    private @NotNull ChatConversation conversation;

    @Enumerated(EnumType.STRING)
    @Column(name = "author_source", nullable = false)
    private @NotNull MessageAuthorSource authorSource;
}
