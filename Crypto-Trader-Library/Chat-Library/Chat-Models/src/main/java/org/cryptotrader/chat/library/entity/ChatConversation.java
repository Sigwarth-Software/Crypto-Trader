package org.cryptotrader.chat.library.entity;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.cryptotrader.api.library.entity.user.ProductUser;
import org.cryptotrader.universal.library.entity.AutoGeneratedIdentifiableEntity;
import org.jetbrains.annotations.NotNull;

import java.util.List;
import java.util.UUID;

/** A conversation with a bot via Crypto-Trader-Chat. */
@Entity
@Table(name = "chat_conversations")
@NoArgsConstructor
@AllArgsConstructor
@Getter
@Setter
public class ChatConversation extends AutoGeneratedIdentifiableEntity {
    @Column(name = "conversation_title", nullable = false)
    private @NotNull String conversationTitle;

    @Column(name = "conversation_id", nullable = false, unique = true)
    private @NotNull UUID conversationId;

    @OneToMany(mappedBy = "conversation")
    private List<ChatConversationMessage> messages;


    @ManyToOne
    @JoinColumn(name = "user_id", nullable = false)
    private ProductUser user;

    public ChatConversation(String conversationTitle, UUID conversationId, ProductUser user) {
        this.conversationTitle = conversationTitle;
        this.conversationId = conversationId;
        this.user = user;
    }
}
