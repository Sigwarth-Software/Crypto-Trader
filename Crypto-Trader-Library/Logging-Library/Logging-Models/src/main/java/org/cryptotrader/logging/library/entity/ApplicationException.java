package org.cryptotrader.logging.library.entity;
import jakarta.persistence.*;
import lombok.*;
import org.cryptotrader.universal.library.entity.AutoGeneratedIdentifiableEntity;
import org.cryptotrader.universal.library.model.annotation.Loggable;
import java.time.LocalDateTime;
@Entity
@Table(name = "application_exceptions")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class ApplicationException extends AutoGeneratedIdentifiableEntity {
    @Column(name = "timestamp")
    private LocalDateTime timestamp;

    @Loggable
    @Enumerated(EnumType.STRING)
    @Column(name = "module")
    private LogModule module;

    @Column(name = "logger")
    private String logger;

    @Loggable
    @Enumerated(EnumType.STRING)
    @Column(name = "level")
    private LogLevel level;

    @Column(name = "thread_name")
    private String threadName;

    @Loggable
    @Column(name = "exception_class")
    private String exceptionClass;

    @Loggable
    @Column(name = "exception_message", columnDefinition = "TEXT")
    private String exceptionMessage;

    @Column(name = "stack_trace", columnDefinition = "TEXT")
    private String stackTrace;

    @Column(name = "root_cause_class")
    private String rootCauseClass;

    @Column(name = "root_cause_message", columnDefinition = "TEXT")
    private String rootCauseMessage;

    @Column(name = "received_at")
    private LocalDateTime receivedAt;
}
