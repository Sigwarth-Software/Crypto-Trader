package org.cryptotrader.logging.library.entity;
import jakarta.persistence.*;
import lombok.*;
import org.cryptotrader.universal.library.entity.AutoGeneratedIdentifiableEntity;
import org.cryptotrader.universal.library.model.annotation.Loggable;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import java.time.LocalDateTime;
@Entity
@Table(name = "application_logs")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class ApplicationLog extends AutoGeneratedIdentifiableEntity {
    @Column(name = "timestamp")
    private LocalDateTime timestamp;

    @Loggable
    @Enumerated(EnumType.STRING)
    @Column(name = "level")
    private LogLevel level;

    @Column(name = "logger")
    private String logger;

    @Loggable
    @Enumerated(EnumType.STRING)
    @Column(name = "module")
    private LogModule module;

    @Column(name = "thread_name")
    private String threadName;

    @Loggable
    @Column(name = "message", columnDefinition = "TEXT")
    private String message;

    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "metadata", columnDefinition = "JSONB")
    private String metadata;

    @Column(name = "error_name")
    private String errorName;

    @Column(name = "error_message", columnDefinition = "TEXT")
    private String errorMessage;

    @Column(name = "error_stack", columnDefinition = "TEXT")
    private String errorStack;

    @Column(name = "received_at")
    private LocalDateTime receivedAt;
}
