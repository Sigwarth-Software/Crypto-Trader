package org.cryptotrader.logging.library.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.cryptotrader.universal.library.entity.AutoGeneratedIdentifiableEntity;
import org.cryptotrader.universal.library.model.annotation.Loggable;

import java.time.LocalDateTime;

@Entity
@Table(name = "execution_speed_logs")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class ExecutionSpeedLog extends AutoGeneratedIdentifiableEntity {
    @Column(name = "timestamp")
    private LocalDateTime timestamp;

    @Loggable
    @Column(name = "execution_speed")
    private long executionSpeed;

    @Loggable
    @Column(name = "expected_execution_speed", nullable = true)
    private Long expectedExecutionSpeed;

    @Column(name = "full_method_qualified_name")
    private String fullMethodQualifiedName;

    @Loggable
    @Column(name = "method_name")
    private String methodName;

    @Loggable
    @Column(name = "class_name")
    private String className;

    @Loggable
    @Enumerated(EnumType.STRING)
    @Column(name = "warning_level")
    private ExecutionSpeedWarningLevel warningLevel;

    public ExecutionSpeedLog(final long executionSpeed,
                             final String fullMethodQualifiedName,
                             final String methodName,
                             final String className) {
        this(LocalDateTime.now(),
            executionSpeed,
            null,
            fullMethodQualifiedName,
            methodName,
            className,
            null);
    }

    public ExecutionSpeedLog(final long executionSpeed,
                             final Long expectedExecutionSpeed,
                             final String fullMethodQualifiedName,
                             final String methodName,
                             final String className) {
        this(LocalDateTime.now(),
            executionSpeed,
            expectedExecutionSpeed,
            fullMethodQualifiedName,
            methodName,
            className,
            null);
    }

    public ExecutionSpeedLog(final long executionSpeed,
                             final Long expectedExecutionSpeed,
                             final String fullMethodQualifiedName,
                             final String methodName,
                             final String className,
                             final LocalDateTime timestamp) {
        this(executionSpeed,
            expectedExecutionSpeed,
            fullMethodQualifiedName,
            methodName,
            className,
            timestamp,
            null);
    }

    public ExecutionSpeedLog(final long executionSpeed,
                             final Long expectedExecutionSpeed,
                             final String fullMethodQualifiedName,
                             final String methodName,
                             final String className,
                             final LocalDateTime timestamp,
                             final ExecutionSpeedWarningLevel warningLevel) {
        this(timestamp,
            executionSpeed,
            expectedExecutionSpeed,
            fullMethodQualifiedName,
            methodName,
            className,
            warningLevel);
    }
}
