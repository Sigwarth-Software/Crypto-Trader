package org.cryptotrader.data.library.entity.news;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.Setter;
import org.cryptotrader.universal.library.entity.AutoGeneratedIdentifiableEntity;
import org.cryptotrader.data.library.entity.news.builder.NewsSentimentBuilder;
import org.cryptotrader.universal.library.model.annotation.Loggable;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.time.LocalDateTime;

@Entity
@Getter
@Setter
@Table(name = "news_sentiments")
public class NewsSentiment extends AutoGeneratedIdentifiableEntity {
    @Column(name = "article_id", unique = true)
    private Long articleId;

    @Loggable
    @Column(name = "article_title")
    private String title;

    @Loggable
    @Column(name = "published_date")
    private @Nullable LocalDateTime publishedDate;

    @Loggable
    @Column(name = "source")
    private String source;

    @Column(name = "url")
    private String url;

    @Loggable
    @Column(name = "positive_score")
    private double positiveScore;

    @Loggable
    @Column(name = "neutral_score")
    private double neutralScore;

    @Loggable
    @Column(name = "negative_score")
    private double negativeScore;

    @Loggable
    @Column(name = "composite_score")
    private double compositeScore;

    @Loggable
    @Column(name = "crypto_relevance")
    private double cryptoRelevance;

    @Column(name = "last_updated")
    private LocalDateTime lastUpdated;

    @Loggable
    @Column(name = "weighted_score")
    private double weightedScore;

    public NewsSentiment() {
        super();
        this.articleId = 0L;
        this.title = "";
        this.publishedDate = null;
        this.source = "";
        this.url = "";
        this.positiveScore = 0;
        this.neutralScore = 0;
        this.negativeScore = 0;
        this.compositeScore = 0;
        this.cryptoRelevance = 0;
        this.weightedScore = 0;
        this.lastUpdated = LocalDateTime.now();
    }

    public NewsSentiment(final Long articleId,
                         final String title,
                         final LocalDateTime publishedDate,
                         final String source,
                         final String url,
                         final double positiveScore,
                         final double neutralScore,
                         final double negativeScore,
                         final double compositeScore,
                         final double cryptoRelevance,
                         final LocalDateTime lastUpdated) {
        super();
        this.articleId = articleId;
        this.title = title;
        this.publishedDate = publishedDate;
        this.source = source;
        this.url = url;
        this.positiveScore = positiveScore;
        this.neutralScore = neutralScore;
        this.negativeScore = negativeScore;
        this.compositeScore = compositeScore;
        this.cryptoRelevance = cryptoRelevance;
        this.lastUpdated = lastUpdated;
        this.weightedScore = calculateWeightedScore(compositeScore, cryptoRelevance);

    }

    public static @NotNull NewsSentimentBuilder builder() {
        return new NewsSentimentBuilder();
    }

    public static double calculateWeightedScore(final double compositeScore, final double cryptoRelevance) {
        return compositeScore * cryptoRelevance;
    }
}


