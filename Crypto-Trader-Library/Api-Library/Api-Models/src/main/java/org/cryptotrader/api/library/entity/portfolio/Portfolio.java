package org.cryptotrader.api.library.entity.portfolio;
//=================================-Imports-==================================

import com.fasterxml.jackson.annotation.JsonBackReference;
import com.fasterxml.jackson.annotation.JsonIdentityInfo;
import com.fasterxml.jackson.annotation.ObjectIdGenerators;
import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;
import org.cryptotrader.api.library.entity.portfolio.builder.PortfolioBuilder;
import org.cryptotrader.api.library.entity.user.ProductUser;
import org.cryptotrader.api.library.model.portfolio.UpdatableValues;
import org.cryptotrader.universal.library.entity.AutoGeneratedIdentifiableEntity;
import org.cryptotrader.universal.library.model.annotation.Loggable;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

@Getter
@Setter
@Entity
@Table(name = "portfolios")
@JsonIdentityInfo(generator = ObjectIdGenerators.PropertyGenerator.class, property = "id")
public class Portfolio extends AutoGeneratedIdentifiableEntity implements UpdatableValues {
    //============================-Variables-=================================
    @JsonBackReference
    @OneToOne(mappedBy = "portfolio")
    private ProductUser user;
    @Loggable
    @Column(name = "dollar_balance", columnDefinition = "DECIMAL(34, 18)")
    private double dollarBalance;
    @Loggable
    @Column(name = "share_balance", columnDefinition = "DECIMAL(34, 18)")
    private double shareBalance;
    @Loggable
    @Column(name = "total_worth", columnDefinition = "DECIMAL(34, 18)")
    private double totalWorth;
    @Column(name = "last_updated")
    private LocalDateTime lastUpdated;
    @OneToMany(mappedBy = "portfolio", fetch = FetchType.LAZY)
    private List<PortfolioAsset> assets;
    @OneToMany(mappedBy = "portfolio", fetch = FetchType.LAZY)
    private List<PortfolioHistory> portfolioHistory;
    //===========================-Constructors-===============================
    public Portfolio() {
        super();
        this.dollarBalance = 0;
        this.shareBalance = 0;
        this.totalWorth = 0;
        this.user = new ProductUser();
        this.assets = new ArrayList<>();
        this.portfolioHistory = new ArrayList<>();
        this.lastUpdated = LocalDateTime.now();
    }
    public Portfolio(final ProductUser user) {
        super();
        this.user = user;
        this.assets = new ArrayList<>();
        this.portfolioHistory = new ArrayList<>();
        this.lastUpdated = LocalDateTime.now();
    }
    public Portfolio(final ProductUser user, final List<PortfolioAsset> assets) {
        super();
        this.user = user;
        this.assets = assets;
        this.portfolioHistory = new ArrayList<>();
        this.updateValues();
    }
    public Portfolio(final double dollarBalance, final double shareBalance, final double totalWorth) {
        super();
        this.user = new ProductUser();
        this.dollarBalance = dollarBalance;
        this.shareBalance = shareBalance;
        this.totalWorth = totalWorth;
        this.assets = new ArrayList<>();
        this.portfolioHistory = new ArrayList<>();
        this.lastUpdated = LocalDateTime.now();
    }

    public Portfolio(final List<PortfolioAsset> assets) {
        super();
        this.user = new ProductUser();
        this.assets = assets;
        this.lastUpdated = LocalDateTime.now();
        this.portfolioHistory = new ArrayList<>();
        this.updateValues();
    }

    public Portfolio(final ProductUser user,
                     final double dollarBalance,
                     final double shareBalance,
                     final double totalWorth,
                     final LocalDateTime lastUpdated,
                     final List<PortfolioAsset> assets,
                     final List<PortfolioHistory> portfolioHistory) {
        super();
        this.user = user;
        this.dollarBalance = dollarBalance;
        this.shareBalance = shareBalance;
        this.totalWorth = totalWorth;
        this.lastUpdated = lastUpdated;
        this.assets = assets;
        this.portfolioHistory = portfolioHistory;
        this.updateValues();
    }

    //=============================-Methods-==================================

    //-----------------------Add-Portfolio-History----------------------------
    public void addPortfolioHistory(final PortfolioHistory portfolioHistory) {
        if (portfolioHistory == null) {
            throw new IllegalArgumentException("Portfolio history cannot be null.");
        }
        this.portfolioHistory.add(portfolioHistory);
    }
    //-----------------------------Add-Asset----------------------------------
    public void addAsset(final PortfolioAsset asset) {
        if (asset == null) {
            throw new IllegalArgumentException("Asset cannot be null.");
        }
        asset.setPortfolio(this);
        this.assets.add(asset);
        this.updateValues();
    }
    //----------------------------Remove-Asset--------------------------------
    public boolean removeAsset(final PortfolioAsset asset) {
        if (asset == null) {
            throw new IllegalArgumentException("Asset cannot be null.");
        }
        final boolean removed = this.assets.remove(asset);
        if (removed) {
            this.updateValues();
        }
        return removed;
    }
    //-------------------------Is-Empty-Portfolio-----------------------------
    public boolean isEmpty() {
        return this.assets.isEmpty();
    }
    //--------------------------------From------------------------------------
    public static Portfolio from(final Portfolio portfolio) {
        final Portfolio newPortfolio = new Portfolio();
        newPortfolio.setId(portfolio.getId());
        newPortfolio.setDollarBalance(portfolio.getDollarBalance());
        newPortfolio.setShareBalance(portfolio.getShareBalance());
        newPortfolio.setTotalWorth(portfolio.getTotalWorth());
        newPortfolio.setLastUpdated(portfolio.getLastUpdated());
        newPortfolio.setAssets(portfolio.getAssets());
        return newPortfolio;
    }

    public static double getTotalPortfolioValue(final List<PortfolioAsset> assets) {
        final double dollarBalance = getTotalDollarValue(assets);
        final double shareBalance = getTotalShareValue(assets);
        return dollarBalance + shareBalance;
    }

    public static double getTotalDollarValue(final List<PortfolioAsset> assets) {
        double dollarBalance = 0;
        for (final PortfolioAsset asset : assets) {
            asset.updateValues();
            dollarBalance += asset.getAssetWalletDollars();
        }
        return dollarBalance;
    }

    public static double getTotalShareValue(final List<PortfolioAsset> assets) {
        double shareBalance = 0;
        for (final PortfolioAsset asset : assets) {
            asset.updateValues();
            shareBalance += asset.getSharesValueInDollars();
        }
        return shareBalance;
    }

    public static PortfolioBuilder builder() {
        return new PortfolioBuilder();
    }

    //============================-Overrides-=================================

    //---------------------------Update-Values--------------------------------
    @Override
    public void updateValues() {
        this.dollarBalance = 0;
        this.shareBalance = 0;
        this.assets.forEach(asset -> {
            asset.updateValues();
            this.dollarBalance += asset.getAssetWalletDollars();
            this.shareBalance += asset.getSharesValueInDollars();
        });
        this.totalWorth = this.dollarBalance + this.shareBalance;
        this.lastUpdated = LocalDateTime.now();
    }
    //------------------------------Equals------------------------------------
    @Override
    public boolean equals(final Object object) {
        if (this == object) return true;
        if (object instanceof final Portfolio portfolio) {
            final boolean sameDollarBalance = this.dollarBalance == portfolio.dollarBalance;
            final boolean sameShareBalance = this.shareBalance == portfolio.shareBalance;
            final boolean sameTotalWorth = this.totalWorth == portfolio.totalWorth;

            final boolean sameAssets = this.assets.equals(portfolio.assets);
            if (this.id != null) {
                if (this.lastUpdated != null) {
                    final boolean sameLastUpdated = this.lastUpdated.equals(portfolio.lastUpdated);
                    return sameDollarBalance && sameShareBalance &&
                            sameTotalWorth && sameLastUpdated && sameAssets;
                } else {
                    final boolean sameId = this.id.equals(portfolio.id);
                    return sameId && sameDollarBalance && sameShareBalance &&
                            sameTotalWorth && sameAssets;
                }
            }
            return sameDollarBalance && sameShareBalance && sameTotalWorth &&
                    sameAssets;
        }
        return false;
    }
    //------------------------------Hash-Code---------------------------------

    //------------------------------To-String---------------------------------
    @Override
    public String toString() {
        final StringBuilder portfolioString = new StringBuilder();
        portfolioString.append("Portfolio ID: ").append(this.id).append("\n");
        portfolioString.append("Dollar Balance: ").append(this.dollarBalance).append("\n");
        portfolioString.append("Share Balance: ").append(this.shareBalance).append("\n");
        portfolioString.append("Total Worth: ").append(this.totalWorth).append("\n");
        portfolioString.append("Assets: ").append("\n");
        final List<PortfolioAsset> portfolioAssets = this.assets;
        for (int i = 0; i < portfolioAssets.size(); i++) {
            final PortfolioAsset asset = portfolioAssets.get(i);
            if (i == portfolioAssets.size() - 1) {
                portfolioString.append(asset);
            } else {
                portfolioString.append(asset.toString()).append("\n");
            }
        }
        return portfolioString.toString();
    }
}
