package org.cryptotrader.api.library.entity.user;
//=================================-Imports-==================================

import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;
import org.cryptotrader.universal.library.entity.AutoGeneratedIdentifiableEntity;
import org.cryptotrader.universal.library.model.annotation.Loggable;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;

import java.time.LocalDateTime;
import java.util.Collection;
import java.util.Collections;

@Getter
@Setter
@MappedSuperclass
public class User extends AutoGeneratedIdentifiableEntity implements UserDetails {
    @Column(name = "username")
    protected @Nullable String username;

    @JsonIgnore
    @Embedded
    @AttributeOverride(
        name = "encodedPassword",
        column = @Column(name = "password_hash")
    )
    protected @Nullable SafePassword safePassword;

    @Column(name = "last_login")
    protected @Nullable LocalDateTime lastLogin;

    @Loggable
    @Enumerated(EnumType.STRING)
    @Column(
        name = "role",
        nullable = false,
        columnDefinition = "varchar(255) default 'USER'"
    )
    private @NotNull UserRoleTier role = UserRoleTier.USER;

    @Column(name = "last_ip_check_timestamp")
    private @Nullable LocalDateTime lastIpCheckTimestamp;

    public User() {
        super();
        this.username = null;
        this.safePassword = new SafePassword();
        this.lastLogin = null;
    }

    public User(@Nullable final String username,
                @NotNull final String rawPassword) {
        super();
        this.username = username;
        this.safePassword = new SafePassword(rawPassword);
        this.lastLogin = LocalDateTime.now();
    }

    public User(@Nullable final String username,
                @NotNull final SafePassword encodedPassword) {
        super();
        this.username = username;
        this.safePassword = encodedPassword;
        this.lastLogin = LocalDateTime.now();
    }

    //=============================-Methods-==================================

    @JsonIgnore
    @Override
    public Collection<? extends GrantedAuthority> getAuthorities() {
        return Collections.singletonList(new SimpleGrantedAuthority(role.getAuthority()));
    }

    @JsonIgnore
    @Override
    public @Nullable String getPassword() {
        if (this.safePassword != null && this.safePassword.getEncodedPassword() != null) {
            return this.safePassword.getEncodedPassword();
        }
        return null;
    }

    @JsonIgnore
    @Override
    public boolean isAccountNonExpired() {
        // TODO: Implement account expiration logic.
        return true;
    }

    @JsonIgnore
    @Override
    public boolean isAccountNonLocked() {
        // TODO: Implement account locking logic.
        return true;
    }

    @JsonIgnore
    @Override
    public boolean isCredentialsNonExpired() {
        // TODO: Implement credential expiration logic.
        return true;
    }

    @JsonIgnore
    @Override
    public boolean isEnabled() {
        // TODO: Implement account enabling/disabling logic.
        return true;
    }

    //-------------------------Update-Login-Time------------------------------
    public void updateLoginTime() {
        this.lastLogin = LocalDateTime.now();
    }
}
