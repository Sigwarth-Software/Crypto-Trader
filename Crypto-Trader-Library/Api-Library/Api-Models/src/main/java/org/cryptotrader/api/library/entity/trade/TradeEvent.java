package org.cryptotrader.api.library.entity.trade;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;
import org.cryptotrader.universal.library.entity.AutoGeneratedIdentifiableEntity;
import org.cryptotrader.api.library.entity.portfolio.Portfolio;
import org.cryptotrader.api.library.entity.portfolio.PortfolioAsset;
import org.cryptotrader.api.library.entity.portfolio.PortfolioAssetHistory;
import org.cryptotrader.universal.library.model.annotation.Loggable;
import org.jetbrains.annotations.NotNull;

import java.time.LocalDateTime;

@Entity
@Getter
@Setter
@Table(name = "trade_events")
public class TradeEvent extends AutoGeneratedIdentifiableEntity {
    @JoinColumn(name = "portfolio_id", nullable = false)
    @ManyToOne
    private Portfolio portfolio;
    @JoinColumn(name = "portfolio_asset_id", nullable = false)
    @ManyToOne
    private PortfolioAsset portfolioAsset;
    @JoinColumn(name = "portfolio_asset_history_id", nullable = false)
    @OneToOne
    private PortfolioAssetHistory assetHistory;
    @Enumerated(EnumType.STRING)
    @Column(name = "trade_type", length = 50, nullable = false)
    @Loggable
    private TradeType tradeType;
    @Loggable
    @Column(name = "value_change", columnDefinition = "DECIMAL(34, 18)")
    private double valueChange;
    @Loggable
    @Column(name = "shares_change", columnDefinition = "DECIMAL(34, 18)")
    private double sharesChange;
    @Column(name = "trade_time", nullable = false)
    private LocalDateTime tradeTime;

    public TradeEvent() {
        super();
    }

    public TradeEvent(final @NotNull PortfolioAssetHistory assetHistory,
                      final TradeType tradeType,
                      final double valueChange,
                      final double sharesChange) {
        this(assetHistory, tradeType, valueChange, sharesChange, LocalDateTime.now());
    }
    public TradeEvent(final @NotNull PortfolioAssetHistory assetHistory,
                      final TradeType tradeType,
                      final double valueChange,
                      final double sharesChange,
                      final LocalDateTime tradeTime) {
        super();
        this.portfolio = assetHistory.getPortfolio();
        this.portfolioAsset = assetHistory.getPortfolioAsset();
        this.assetHistory = assetHistory;
        this.tradeType = tradeType;
        this.valueChange = valueChange;
        this.sharesChange = sharesChange;
        this.tradeTime = tradeTime;
    }

    public static @NotNull TradeType getTradeType(final @NotNull PortfolioAssetHistory portfolioAssetHistory) {
        return portfolioAssetHistory.getShares() > 0 ? TradeType.BUY : TradeType.SELL;
    }
}
