package org.cryptotrader.api.library.entity.user;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;
import org.cryptotrader.universal.library.entity.AutoGeneratedIdentifiableEntity;

import java.time.LocalDateTime;

// TODO: Implement this.
@Table(name = "subscription_changes")
@Entity
@Getter
@Setter
public class SubscriptionChange extends AutoGeneratedIdentifiableEntity {
    @ManyToOne
    @JoinColumn(name = "user_id", nullable = false)
    private ProductUser user;

    @Column(name = "timestamp", nullable = false)
    private LocalDateTime timestamp;

    @Enumerated(EnumType.STRING)
    @Column(name = "previous_tier", nullable = false)
    private SubscriptionTier previousTier;

    @Enumerated(EnumType.STRING)
    @Column(name = "new_tier", nullable = false)
    private SubscriptionTier newTier;
}


