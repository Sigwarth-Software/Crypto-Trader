package org.cryptotrader.development.library.model

import java.time.LocalDateTime
import java.time.format.DateTimeFormatter

open class DevelopmentIssue(
    val issueTitle: String,
    val issueDescription: String,
    val labels: List<String>,
    val points: Int,
    val extraContent: String? = null
) : IssueDescriptive, GenerativeContentDisclaimer {
    override fun getDescription(): String {
        val hasExtraContent: Boolean = !this.extraContent.isNullOrBlank()

        val sections: MutableList<String> = mutableListOf(this.issueTitle, this.issueDescription)
        if (hasExtraContent) {
            sections.add(this.extraContent!!)
        }
        sections.add("Points: ${this.points}")
        sections.add(this.getGenerativeContentDisclaimer())

        return sections.joinToString(separator = "\n\n")
    }

    override fun getGenerativeContentDisclaimer(): String {
        val disclaimerFormat = "HH:mm:ss MM/dd/yyyy"
        val dateTimeFormatter: DateTimeFormatter = DateTimeFormatter.ofPattern(
            disclaimerFormat
        )
        val formattedDateTime: String = LocalDateTime.now().format(
            dateTimeFormatter
        )
        return """
            _This content was generated by Crypto-Trader-Development at $formattedDateTime._
            _AI can make mistakes, so please contact the owners for verification._
        """.trimIndent()
    }
}