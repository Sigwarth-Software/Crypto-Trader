package org.cryptotrader.agent.library.entity;

import com.fasterxml.jackson.databind.JsonNode;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.cryptotrader.agent.library.model.AgentTool;
import org.cryptotrader.universal.library.entity.AutoGeneratedIdentifiableEntity;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.time.LocalDateTime;

@Entity
@Table(name = "agent_tool_executions")
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
public class AgentToolExecution extends AutoGeneratedIdentifiableEntity {
    @Enumerated(EnumType.STRING)
    @Column(name = "tool")
    private @NotNull AgentTool tool;

    @Column(name = "execution_time")
    private @Nullable LocalDateTime executionTime;

    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "input", columnDefinition = "jsonb")
    private @Nullable JsonNode input;

    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "output", columnDefinition = "jsonb")
    private @Nullable JsonNode output;

    @Column(name = "duration_ms")
    private @Nullable Long durationMs;

    @Column(name = "is_success")
    private boolean isSuccess;
}
